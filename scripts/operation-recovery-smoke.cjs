const { chromium } = require("playwright");
const assert = require("node:assert/strict");

(async () => {
  const base = process.argv[2];
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_BROWSER_CHANNEL || undefined });
  try {
    const context = await browser.newContext({ viewport: { width: 320, height: 700 } });
    let page = await context.newPage();
    const errors = [];
    const trackErrors = page => page.on("pageerror", error => errors.push(error.message));
    trackErrors(page);
    await page.goto(`${base}/login`);
    await page.getByLabel("Admin password").fill("pw");
    await page.getByRole("button", { name: "Login", exact: true }).click();
    await page.locator('details[data-project="web"] > summary').click();
    await page.getByRole("button", { name: "Upgrade", exact: true }).click();
    await page.waitForURL(url => !!url.searchParams.get("job"));
    const id = new URL(page.url()).searchParams.get("job");
    await page.reload();
    assert.equal(await page.locator("[data-operation-status]").textContent(), "running");
    await page.close();
    await context.request.post(`${base}/test-ui-restart`);
    page = await context.newPage();
    trackErrors(page);
    await page.goto(`${base}/?host=local`);
    assert.equal(new URL(page.url()).searchParams.has("job"), false);
    assert((await page.locator("[data-operation-url]").getAttribute("data-operation-url")).includes(id));
    assert.equal(await page.getByLabel("Operation output").textContent(), "Compose pull running");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "real container ID overflows mobile operation panel");
    await page.getByRole("link", { name: "Close output", exact: true }).click();
    const stack = page.locator('details[data-project="web"]');
    if (!(await stack.evaluate(item => item.open))) await stack.locator(":scope > summary").click();
    await stack.locator(".secondary-actions > summary").click();
    await stack.getByLabel("Target").selectOption("stack");
    await stack.getByLabel("Target").focus();
    await page.request.post(`${base}/test-finish`);
    await page.waitForFunction(() => document.querySelector("[data-operation-status]").textContent === "success");
    await page.waitForFunction(() => document.querySelector("[data-ui-status]").textContent.includes("paused"));
    assert.equal(await stack.getByLabel("Target").inputValue(), "stack");
    assert.equal(await page.getByText("web-original", { exact: true }).isVisible(), true, "refresh interrupted form editing");
    await stack.locator(":scope > summary").focus();
    await page.getByText("web-updated", { exact: true }).waitFor();
    assert.equal(await stack.locator(":scope > summary").evaluate(item => item === document.activeElement), true, "refresh lost keyboard focus");
    assert.equal(await stack.locator(".secondary-actions").evaluate(item => item.open), true, "refresh collapsed secondary actions");
    assert.equal(await stack.getByLabel("Target").inputValue(), "stack", "refresh reset target selection");
    assert.equal(await page.getByLabel("Operation output").isVisible(), false, "completion reopened hidden output");
    await page.getByRole("link", { name: "Show output", exact: true }).click();
    assert.equal(await page.getByLabel("Operation output").textContent(), "Compose upgrade completed");
    await page.goto(`${base}/?host=local&view=cleanup`);
    await page.getByRole("link", { name: "Close output", exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.get("view"), "cleanup", "output toggle changed screens");
    await page.reload();
    assert.equal(await page.getByRole("heading", { level: 1 }).textContent(), "Cleanup");
    assert.equal(await page.getByLabel("Operation output").isVisible(), false);
    const deletion = page.getByRole("form", { name: "Delete volume recovery-volume", exact: true });
    await deletion.getByRole("checkbox").check();
    await deletion.getByRole("button", { name: "Delete", exact: true }).click();
    await page.waitForURL(url => url.searchParams.get("view") === "cleanup" && url.searchParams.get("job") !== id);
    assert.equal(await page.getByRole("heading", { level: 1 }).textContent(), "Cleanup", "cleanup action returned to containers");
    await page.request.post(`${base}/test-finish`);
    await page.waitForFunction(() => document.querySelector("[data-operation-status]").textContent === "success");
    await page.getByText("recovery-volume", { exact: true }).waitFor({ state: "detached" });
    assert.equal(await page.getByRole("heading", { level: 1 }).textContent(), "Cleanup");
    assert.equal(await page.getByRole("form", { name: "Remove all unused Volumes", exact: true }).getByRole("button").isDisabled(), true, "cleanup retained stale unused resources");
    assert.deepEqual(errors, []);
    await context.close();
    console.log("PASS recovery: reload, closed tab, recreated UI, no job URL, mobile layout, current state, one upgrade and one cleanup, cleanup destination preserved");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
